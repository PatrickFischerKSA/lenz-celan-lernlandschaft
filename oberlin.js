function oberlinObjectPanel(){const o=oberlinObjects.find(o=>o.id===oberlinSelected)||oberlinObjects[0],theme=oberlinThemes.find(t=>t.id===o.group);return `<div class="oberlin-object"><div class="oberlin-object-copy"><p class="eyebrow">${theme.label} · ${escapeHTML(o.date)}</p><h3>${escapeHTML(o.title)}</h3><p>${escapeHTML(o.text)}</p><p class="oberlin-look"><strong>Schau genauer hin:</strong> ${escapeHTML(o.question)}</p><p>${theme.text}</p><div class="atlas-detail-links"><a href="${theme.reading}">${theme.readingLabel} ↗</a><a href="${o.source}" target="_blank" rel="noreferrer">Die Erklärung des Museums lesen ↗</a></div>${o.id==='schaedel'?`<p class="source">Zur Einordnung der Phrenologie: ${link('https://exhibitions.ed.ac.uk/exhibitions/mind-shift','Universität Edinburgh: Mind Shift')}.</p>`:''}</div><div class="oberlin-object-images">${o.images.map((src,i)=>`<figure><a href="${src}" target="_blank" rel="noreferrer" aria-label="${escapeHTML(o.title)}${o.images.length>1?' · Abbildung '+(i+1):''} in voller Grösse öffnen"><img src="${src}" alt="${escapeHTML(o.title)} · ${escapeHTML(o.date)}${o.images.length>1?' · Abbildung '+(i+1):''}" loading="lazy" decoding="async" referrerpolicy="no-referrer"></a><figcaption>${escapeHTML(o.credit)}. <a href="${o.source}" target="_blank" rel="noreferrer">Objektseite und Bildnachweis</a> · <a href="${src}" target="_blank" rel="noreferrer">Bild vergrössern</a></figcaption></figure>`).join('')}</div></div>`;}
function oberlinResources(){return `<details class="oberlin-more"><summary>Noch mehr aus dem Museum: Gärten, Bücher und Lenz</summary><ul><li>${link('https://musee-oberlin.org/de/entdecken/johann-friedrich-oberlin/','Oberlins Leben und sein Einsatz für das Steintal')}</li><li>${link('https://musee-oberlin.org/de/entdecken/die-gaerten-und-herbarien/','Gärten und Herbarien: Pflanzenwissen, Alltag und Heilen')}</li><li>${link('https://musee-oberlin.org/de/entdecken/die-bibliothek/','Die Bibliothek: Lesen und Wissen teilen')}</li><li>${link('https://musee-oberlin.org/de/entdecken/austellungen/vergangene-ausstellungen/lenz-mythos-und-realitaet/','Die frühere Ausstellung «Lenz, Mythos und Realität»')}</li><li>${link('https://musee-oberlin.org/de/entdecken/austellungen/vergangene-ausstellungen/von-der-tollkirsche-zum-salbei/','Die frühere Ausstellung über Pflanzen, Glaube und Heilen')}</li><li>${link('https://musee-oberlin.org/wp-content/uploads/2018/07/Fondation_Oberlin_DE.pdf','Deutschsprachige Museumsbroschüre · PDF')}</li><li>${link('https://musee-oberlin.org/wp-content/uploads/2018/11/oberlin_bibliotheque_inventaire.pdf','Bestandsverzeichnis der Bibliothek und Archive · französisch, PDF')}</li><li>${link('https://musee-oberlin.org/de/teilen/museumsgefluester/','Oberlins Wetter- und Landschaftsbeobachtung vom November 1774')}</li></ul><p class="source">Die Museumstexte und Bildnachweise bleiben bei den Quellen zugänglich. Unsere Fragen verbinden die Gegenstände mit den Texten; sie behaupten keinen nachgewiesenen Bezug Celans auf diese einzelnen Objekte.</p></details>`;}
function oberlinCollections(){return `<section class="oberlin-collections" id="oberlin-sammlung" aria-labelledby="oberlin-collection-title"><p class="eyebrow">Aus dem Musée Oberlin</p><h2 id="oberlin-collection-title">Was Oberlin aufbewahrt.</h2><p>Karten, Pflanzen, Schattenbilder, Spiele: 25 Gegenstände und Gruppen erzählen davon, wie Oberlin die Welt zeigen und Menschen verstehen wollte. Wähle etwas aus und lege eine Passage von Büchner oder Celan daneben.</p><p class="source">Die Bilder und Objektangaben stammen aus ${link('https://musee-oberlin.org/de/entdecken/die-sammlungen/','der Sammlung des Musée Oberlin')}. Viele Stücke entstanden erst nach Lenz’ Aufenthalt von 1778. Sie zeigen Oberlins spätere Arbeit; sie belegen nicht, dass Lenz diese Gegenstände gesehen oder benutzt hat.</p><div class="oberlin-themes" role="group" aria-label="In Oberlins Sammlung stöbern"><button type="button" data-oberlin-group="alle" aria-pressed="${oberlinGroup==='alle'}">Alles ansehen</button>${oberlinThemes.map(t=>`<button type="button" data-oberlin-group="${t.id}" aria-pressed="${oberlinGroup===t.id}">${t.label}</button>`).join('')}</div><div class="oberlin-browse"><label for="oberlin-object-select">Was möchtest du ansehen?</label><select id="oberlin-object-select">${oberlinVisible().map(o=>`<option value="${o.id}" ${o.id===oberlinSelected?'selected':''}>${escapeHTML(o.title)}</option>`).join('')}</select><div><button type="button" data-oberlin-step="-1" aria-label="Vorherigen Gegenstand ansehen">← Zurück</button><span id="oberlin-object-status" role="status"></span><button type="button" data-oberlin-step="1" aria-label="Nächsten Gegenstand ansehen">Weiter →</button></div></div><div id="oberlin-object-panel">${oberlinObjectPanel()}</div><details class="oberlin-inventory"><summary>Alle 25 Einträge der Museumsseite auf einen Blick</summary><ol>${oberlinObjects.map(o=>`<li><button type="button" data-oberlin-object="${o.id}">${escapeHTML(o.title)}</button> <span>${escapeHTML(o.date)}</span></li>`).join('')}</ol></details>${field('oberlinobjekte')}${oberlinResources()}</section>`;}
function renderOberlinCollection(){const panel=document.getElementById('oberlin-object-panel');if(!panel)return;const list=oberlinVisible();if(!list.some(o=>o.id===oberlinSelected))oberlinSelected=list[0].id;document.getElementById('oberlin-object-select').innerHTML=list.map(o=>`<option value="${o.id}" ${o.id===oberlinSelected?'selected':''}>${escapeHTML(o.title)}</option>`).join('');panel.innerHTML=oberlinObjectPanel();document.getElementById('oberlin-object-status').textContent=`${list.findIndex(o=>o.id===oberlinSelected)+1} von ${list.length}`;main.querySelectorAll('[data-oberlin-group]').forEach(b=>b.setAttribute('aria-pressed',String(b.dataset.oberlinGroup===oberlinGroup)));}
function initOberlinCollection(page,parts){if(page!=='elsass')return;const id=parts[2];if(id&&oberlinObjects.some(o=>o.id===id)){oberlinSelected=id;oberlinGroup='alle';}renderOberlinCollection();if(parts[1]==='sammlung')document.getElementById('oberlin-sammlung')?.scrollIntoView({block:'start',behavior:'instant'});}
function handleOberlinClick(el){
 if(el.dataset.oberlinGroup){oberlinGroup=el.dataset.oberlinGroup;renderOberlinCollection();}
 if(el.dataset.oberlinObject){oberlinSelected=el.dataset.oberlinObject;oberlinGroup='alle';renderOberlinCollection();document.getElementById('oberlin-object-select')?.focus();}
 if(el.dataset.oberlinStep){const list=oberlinVisible(),i=list.findIndex(o=>o.id===oberlinSelected);oberlinSelected=list[(i+Number(el.dataset.oberlinStep)+list.length)%list.length].id;renderOberlinCollection();}
}
